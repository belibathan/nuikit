import {
  AnchorIcon,
  BookOpenIcon,
  BriefcaseIcon,
  Building2Icon,
  CarIcon,
  CompassIcon,
  FerrisWheelIcon,
  FuelIcon,
  HospitalIcon,
  HouseIcon,
  InfoIcon,
  LandmarkIcon,
  MapPinIcon,
  MountainIcon,
  PlaneIcon,
  ScrollTextIcon,
  ShieldIcon,
  ShoppingBagIcon,
  StoreIcon,
  TentIcon,
  TreesIcon,
  UtensilsIcon,
  WarehouseIcon,
  WrenchIcon,
  type LucideIcon,
} from "lucide-react";

/** The lucide icons a config can name (kebab-case, as on lucide.dev). Anything else is a pin. */
const ICONS: Record<string, LucideIcon> = {
  anchor: AnchorIcon,
  "book-open": BookOpenIcon,
  briefcase: BriefcaseIcon,
  building: Building2Icon,
  car: CarIcon,
  compass: CompassIcon,
  "ferris-wheel": FerrisWheelIcon,
  fuel: FuelIcon,
  hospital: HospitalIcon,
  house: HouseIcon,
  info: InfoIcon,
  landmark: LandmarkIcon,
  "map-pin": MapPinIcon,
  mountain: MountainIcon,
  plane: PlaneIcon,
  "scroll-text": ScrollTextIcon,
  shield: ShieldIcon,
  "shopping-bag": ShoppingBagIcon,
  store: StoreIcon,
  tent: TentIcon,
  trees: TreesIcon,
  utensils: UtensilsIcon,
  warehouse: WarehouseIcon,
  wrench: WrenchIcon,
};

export function icon(name: string | undefined, fallback: LucideIcon = MapPinIcon): LucideIcon {
  return (name && ICONS[name]) || fallback;
}
