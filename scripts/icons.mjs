// The kit's one icon set (Hugeicons) under lucide's names: scans every source for the icons it imports (from
// "@/components/ui/icons" or "lucide-react", which every in-repo UI resolves to the same file) and writes
// registry/nuikit/ui/icons.tsx with exactly those, each drawn by its Hugeicon. `pnpm sync` runs it, so using a new
// lucide name anywhere just works; a name Hugeicons spells differently goes in RENAME below.
//
//   node scripts/icons.mjs [--check]
import fs from "node:fs";
import path from "node:path";
import { execSync } from "node:child_process";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = "registry/nuikit/ui/icons.tsx";
// the free set, from the site's install (every UI lists @hugeicons/core-free-icons)
const H = createRequire(path.join(root, "apps/www/package.json"))("@hugeicons/core-free-icons");

/** lucide name → Hugeicon, where the names differ (the rest match by name, then by a 01 variant). */
const RENAME = {
  ArrowBigLeftIcon: "ArrowLeft02Icon",
  ArrowBigRightIcon: "ArrowRight02Icon",
  Building2: "Building03Icon",
  Building2Icon: "Building03Icon",
  ChevronsUpDown: "UnfoldMoreIcon",
  ChevronsUpDownIcon: "UnfoldMoreIcon",
  CircleAlertIcon: "AlertCircleIcon",
  CircleHelpIcon: "HelpCircleIcon",
  Loader2Icon: "Loading03Icon",
  PalmtreeIcon: "TreePalmIcon",
  Repeat2: "RepeatIcon",
  Trash2: "Delete02Icon",
  Trash2Icon: "Delete02Icon",
  UnlockIcon: "SquareUnlock02Icon",
  Volume2Icon: "VolumeHighIcon",
  WineIcon: "DrinkIcon",
};
const OWN = new Set(["Icon", "IconProps", "IconComponent", "LucideIcon", "LucideProps"]);

const files = execSync("git ls-files -co --exclude-standard", { cwd: root, encoding: "utf8" })
  .split("\n")
  .filter((f) => /\.tsx?$/.test(f) && !f.startsWith("fivem-foundation/") && !f.endsWith("components/ui/icons.tsx") && !/\/(dist|build|node_modules)\//.test(f));
const used = new Set();
for (const f of files) {
  const p = path.join(root, f);
  if (!fs.existsSync(p)) continue;
  for (const m of fs.readFileSync(p, "utf8").matchAll(/import\s*\{([^}]*)\}\s*from\s*["'](?:lucide-react|@\/components\/ui\/icons)["']/g))
    for (const part of m[1].split(",")) {
      const n = part.trim().replace(/^type\s+/, "").split(/\s+as\s+/)[0].trim();
      if (n && !OWN.has(n)) used.add(n);
    }
}
const resolve = (n) => {
  const base = n.endsWith("Icon") ? n : `${n}Icon`;
  const stem = base.replace(/Icon$/, "");
  return [RENAME[n], base, `${stem}01Icon`, `${stem.replace(/\d+$/, "")}Icon`, `${stem.replace(/\d+$/, "")}01Icon`].find((x) => x && H[x]);
};
const rows = [...used].sort().map((n) => [n, resolve(n)]);
const missing = rows.filter(([, h]) => !h).map(([n]) => n);
if (missing.length) {
  console.error(`scripts/icons.mjs: no Hugeicon for ${missing.join(", ")}: add them to RENAME`);
  process.exit(1);
}
const hs = [...new Set(rows.map(([, h]) => h))].sort();
const text = `// Generated by scripts/icons.mjs (pnpm sync) from the icons the sources import. Never edit by hand: add a name to
// RENAME there when Hugeicons spells it differently.
import * as React from "react"
import { HugeiconsIcon, type IconSvgElement } from "@hugeicons/react"
import {
${hs.map((h) => `  ${h} as H_${h},`).join("\n")}
} from "@hugeicons/core-free-icons"

/**
 * Icons — the kit's one icon set: Hugeicons (free, stroke rounded) under lucide's names, at the kit's stroke
 * (--nk-icon-stroke). Every nuikit component, block, system and override imports its icons from here, and
 * \`lucide-react\` resolves to this file in every UI, so stock shadcn draws Hugeicons too without an edit. A shadcn
 * snippet pastes in unchanged; swapping the whole set is this one file.
 *
 *   import { SearchIcon, XIcon } from "@/components/ui/icons"
 *   <SearchIcon className="size-(--nk-icon-md)" />
 *   <Icon icon={Car01Icon} />            // any other Hugeicon (import it from @hugeicons/core-free-icons)
 *
 * Role: The one icon set, by lucide's names.
 * Anatomy: svg (data-slot=icon)
 * Props: size, strokeWidth, className, any svg prop.
 * Rules: Icons come from here, never from an icon package directly; sizes from --nk-icon-*; colour is currentColor.
 */

type IconProps = React.ComponentProps<"svg"> & {
  /** Width and height (a CSS length or px). Default 24; usually a size-* class sets it. */
  size?: number | string
}
/** Any icon of the set (lucide's LucideIcon). */
type IconComponent = React.FC<IconProps>

/** Any Hugeicon, at the kit's stroke (an explicit strokeWidth wins: data-stroke). */
function Icon({ icon, size = 24, strokeWidth, ref, ...props }: IconProps & { icon: IconSvgElement }) {
  return (
    <HugeiconsIcon
      ref={ref as React.Ref<SVGSVGElement>}
      icon={icon}
      size={size}
      strokeWidth={strokeWidth === undefined ? undefined : Number(strokeWidth)}
      data-slot="icon"
      data-stroke={strokeWidth === undefined ? undefined : ""}
      {...(props as object)}
    />
  )
}

function make(icon: IconSvgElement, name: string): IconComponent {
  const C = (props: IconProps) => <Icon icon={icon} {...props} />
  C.displayName = name
  return C
}

${rows.map(([n, h]) => `const ${n} = make(H_${h}, "${n}")`).join("\n")}

export {
  Icon,
${rows.map(([n]) => `  ${n},`).join("\n")}
  type IconProps,
  type IconComponent,
  type IconComponent as LucideIcon,
  type IconProps as LucideProps,
}
`;
const dest = path.join(root, OUT);
const before = fs.existsSync(dest) ? fs.readFileSync(dest, "utf8") : "";
if (process.argv.includes("--check")) {
  if (before !== text) (console.error(`${OUT} is stale: run pnpm sync`), process.exit(1));
} else if (before !== text) fs.writeFileSync(dest, text);
console.log(`✓ icons: ${rows.length} names, ${hs.length} Hugeicons`);
