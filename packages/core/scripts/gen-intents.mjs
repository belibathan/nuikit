// Intent schemas → generated code (docs/intents.md §2). One source of truth: packages/core/src/spec/api/intents/*.json.
//
//   node scripts/gen-intents.mjs          (pnpm intents, and part of the core build)
//
// Emits:
//   src/intents.generated.ts   TypeScript types per intent + the schemas as a const (the TS validator reads them)
//   lua/intents.schema.lua     the same schemas as a Lua table + LuaLS ---@class annotations for `nk`
//
// Both files are committed, so typecheck and LuaLS work without a build. Never edit them by hand.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const dir = `${root}src/spec/api/intents/`;

const defs = JSON.parse(readFileSync(`${dir}_defs.json`, "utf8")).defs;
const intents = readdirSync(dir)
  .filter((f) => f.endsWith(".json") && !f.startsWith("_"))
  .map((f) => JSON.parse(readFileSync(dir + f, "utf8")))
  .sort((a, b) => a.name.localeCompare(b.name));

// Fixed order (the catalogue's order in docs/architecture.md §2).
const ORDER = ["notify", "menu", "input", "confirm", "progress", "prompt", "target", "radial", "challenge"];
intents.sort((a, b) => ORDER.indexOf(a.name) - ORDER.indexOf(b.name));
for (const name of ORDER) if (!intents.some((i) => i.name === name)) throw new Error(`missing intents/${name}.json`);

const pascal = (s) => s.replace(/(^|[-_])(\w)/g, (_, __, c) => c.toUpperCase());
const singular = { items: "Item", fields: "Field", options: "Option" };

// ───────────────────────────────── validation of the schemas themselves

const TYPES = new Set(["string", "number", "integer", "boolean", "enum", "array", "object", "any", "oneOf", "ref", "self"]);
function checkType(t, where) {
  if (!t || typeof t !== "object" || !TYPES.has(t.type)) throw new Error(`${where}: bad type ${JSON.stringify(t)}`);
  if (t.type === "ref" && !defs[t.ref]) throw new Error(`${where}: unknown ref ${t.ref}`);
  if (t.type === "enum" && (!Array.isArray(t.values) || !t.values.length)) throw new Error(`${where}: enum needs values`);
  if (t.type === "array") checkType(t.items, `${where}[]`);
  if (t.type === "oneOf") t.of.forEach((o, i) => checkType(o, `${where}|${i}`));
  if (t.type === "object") for (const [k, p] of Object.entries(t.props ?? {})) checkType(p, `${where}.${k}`);
}
for (const [k, d] of Object.entries(defs)) checkType(d, `defs.${k}`);
for (const it of intents) {
  if (typeof it.version !== "number") throw new Error(`${it.name}: version`);
  for (const [k, p] of Object.entries(it.props)) checkType(p, `${it.name}.${k}`);
  if (it.result) checkType(it.result, `${it.name}.result`);
  for (const [k, e] of Object.entries(it.events ?? {})) checkType(e.data, `${it.name}.events.${k}`);
}

// ───────────────────────────────── TypeScript

const tsDoc = (doc, indent = "") => (doc ? `${indent}/** ${doc.replace(/\*\//g, "* /")} */\n` : "");

/** Named types collected while walking (nested item types, shared defs). */
const named = [];
const defName = (ref) => `Intent${pascal(ref)}`;

function tsType(t, ctx) {
  switch (t.type) {
    case "string":
      return "string";
    case "number":
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "any":
      return "unknown";
    case "enum":
      return t.values.map((v) => JSON.stringify(v)).join(" | ");
    case "ref":
      return defName(t.ref);
    case "self":
      return ctx.self ?? "unknown";
    case "oneOf":
      return t.of.map((o) => tsType(o, ctx)).join(" | ");
    case "array": {
      const inner = tsType(t.items, ctx);
      return /[|&]/.test(inner) ? `(${inner})[]` : `${inner}[]`;
    }
    case "object": {
      const entries = Object.entries(t.props ?? {});
      if (!entries.length) return t.open ? "Record<string, unknown>" : "Record<string, never>";
      return tsObject(t, ctx, "  ");
    }
  }
  throw new Error(`tsType ${t.type}`);
}

function tsObject(t, ctx, indent) {
  const lines = [];
  for (const [k, p] of Object.entries(t.props)) {
    let type;
    if (p.type === "array" && p.items.type === "object" && singular[k] && ctx.intent) {
      // A named item type: MenuItem, InputField, TargetOption.
      const name = `${pascal(ctx.intent)}${singular[k]}`;
      if (!named.some((n) => n.name === name)) {
        named.push({ name, body: null });
        const body = tsObject(p.items, { ...ctx, self: name }, "  ");
        named.find((n) => n.name === name).body = body;
      }
      type = `${name}[]`;
    } else {
      type = tsType(p, ctx);
    }
    lines.push(`${tsDoc(p.doc, indent)}${indent}${k}${p.required ? "" : "?"}: ${type};`);
  }
  if (t.open) lines.push(`${indent}[key: string]: unknown;`);
  return `{\n${lines.join("\n")}\n${indent.slice(2)}}`;
}

let ts = `// Generated by scripts/gen-intents.mjs from packages/core/src/spec/api/intents/*.json. Do not edit.
// The nine intents of docs/architecture.md §2: types for scripts, renderers and adapters.
// Validation: src/intents.ts (validateIntent). Lua: lua/intents.schema.lua.

`;
for (const [k, d] of Object.entries(defs)) {
  ts += `${tsDoc(d.doc)}export type ${defName(k)} = ${tsType(d, {})};\n\n`;
}
const kinds = intents.map((i) => i.name);
for (const it of intents) {
  const P = pascal(it.name);
  const before = named.length;
  const props = tsObject({ props: it.props }, { intent: it.name, self: `${P}Props` }, "  ");
  for (const n of named.slice(before)) ts += `export interface ${n.name} ${n.body}\n\n`;
  ts += `${tsDoc(`${it.doc} (v${it.version})`)}export interface ${P}Props ${props}\n\n`;
  ts += `export type ${P}Result = ${it.result ? tsType(it.result, { intent: it.name }) : "void"};\n\n`;
  const events = Object.entries(it.events ?? {});
  ts += `export interface ${P}Events ${events.length ? `{\n${events.map(([k, e]) => `${tsDoc(e.doc, "  ")}  ${k}: ${tsType(e.data, { intent: it.name })};`).join("\n")}\n}` : "{}"}\n\n`;
}
ts += `export type IntentKind = ${kinds.map((k) => JSON.stringify(k)).join(" | ")};\n\n`;
ts += `export const INTENT_KINDS: readonly IntentKind[] = ${JSON.stringify(kinds)};\n\n`;
ts += `export interface IntentProps {\n${kinds.map((k) => `  ${k}: ${pascal(k)}Props;`).join("\n")}\n}\n\n`;
ts += `export interface IntentResults {\n${kinds.map((k) => `  ${k}: ${pascal(k)}Result;`).join("\n")}\n}\n\n`;
ts += `export interface IntentEvents {\n${kinds.map((k) => `  ${k}: ${pascal(k)}Events;`).join("\n")}\n}\n\n`;
ts += `/** Schema versions, one per intent (docs/intents.md §2). */\nexport const INTENT_VERSIONS: Record<IntentKind, number> = ${JSON.stringify(Object.fromEntries(intents.map((i) => [i.name, i.version])))};\n\n`;
ts += `/** Which intents yield a result (the Lua call waits) and which accept update(). */\nexport const INTENT_META: Record<IntentKind, { yields: boolean; update: boolean }> = ${JSON.stringify(Object.fromEntries(intents.map((i) => [i.name, { yields: !!it(i).yields, update: !!it(i).update }])))};\n\n`;
function it(i) {
  return i;
}
ts += `/** The shared type definitions (\`ref\`). */\nexport const INTENT_DEFS = ${JSON.stringify(defs, null, 2)} as const;\n\n`;
ts += `/** The schemas, as written (props, result, events). */\nexport const INTENT_SCHEMAS = ${JSON.stringify(Object.fromEntries(intents.map((i) => [i.name, { name: i.name, version: i.version, yields: !!i.yields, update: !!i.update, props: i.props, result: i.result, events: i.events ?? {} }])), null, 2)} as const;\n`;
writeFileSync(`${root}src/intents.generated.ts`, ts);

// ───────────────────────────────── Lua

const luaStr = (s) => `'${String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\n/g, "\\n")}'`;
function luaValue(v, indent = "") {
  if (v === null || v === undefined) return "nil";
  if (typeof v === "string") return luaStr(v);
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (Array.isArray(v)) return `{ ${v.map((x) => luaValue(x, indent)).join(", ")} }`;
  const entries = Object.entries(v);
  if (!entries.length) return "{}";
  const inner = indent + "  ";
  return `{\n${entries.map(([k, x]) => `${inner}${/^[A-Za-z_]\w*$/.test(k) ? k : `[${luaStr(k)}]`} = ${luaValue(x, inner)},`).join("\n")}\n${indent}}`;
}

function luaType(t, ctx) {
  switch (t.type) {
    case "string":
      return "string";
    case "number":
    case "integer":
      return t.type;
    case "boolean":
      return "boolean";
    case "any":
      return "any";
    case "enum":
      return t.values.map((v) => luaStr(v)).join("|");
    case "ref":
      return `Nk${pascal(t.ref)}`;
    case "self":
      return ctx.self ?? "table";
    case "oneOf":
      return t.of.map((o) => luaType(o, ctx)).join("|");
    case "array": {
      const inner = luaType(t.items, ctx);
      return inner.includes("|") ? `(${inner})[]` : `${inner}[]`;
    }
    case "object": {
      const entries = Object.entries(t.props ?? {});
      if (!entries.length) return "table<string, any>";
      return `{ ${entries.map(([k, p]) => `${k}${p.required ? "" : "?"}: ${luaType(p, ctx)}`).join(", ")} }`;
    }
  }
  throw new Error(`luaType ${t.type}`);
}

const luaClasses = [];
function luaClass(name, t, ctx, doc) {
  const lines = [...(doc ? [`--- ${doc}`] : []), `---@class ${name}`];
  for (const [k, p] of Object.entries(t.props)) {
    let type;
    if (p.type === "array" && p.items.type === "object" && singular[k] && ctx.intent) {
      const n = `Nk${pascal(ctx.intent)}${singular[k]}`;
      if (!luaClasses.some((c) => c.startsWith(`---@class ${n}\n`) || c.includes(`\n---@class ${n}\n`))) luaClass(n, p.items, { ...ctx, self: n }, p.doc);
      type = `${n}[]`;
    } else type = luaType(p, ctx);
    lines.push(`---@field ${k}${p.required ? "" : "?"} ${type}${p.doc ? `  ${p.doc}` : ""}`);
  }
  luaClasses.push(lines.join("\n"));
}

for (const [k, d] of Object.entries(defs)) {
  if (d.type === "object") luaClass(`Nk${pascal(k)}`, d, {}, d.doc);
  else luaClasses.push(`---${d.doc ? ` ${d.doc}` : ""}\n---@alias Nk${pascal(k)} ${luaType(d, {})}`);
}
for (const it of intents) {
  const P = pascal(it.name);
  luaClass(`Nk${P}Props`, { props: it.props }, { intent: it.name, self: `Nk${P}Props` }, `${it.doc} (v${it.version})`);
  luaClasses.push(`---@alias Nk${P}Result ${it.result ? luaType(it.result, { intent: it.name }) : "nil"}`);
}

let lua = `--[[
  intents.schema.lua: generated by packages/core/scripts/gen-intents.mjs from packages/core/src/spec/api/intents/*.json.
  Do not edit. The schemas the Lua validator (intents.lua) reads, and LuaLS types for nk.* (docs/intents.md).
]]

${luaClasses.join("\n\n")}

return {
  defs = ${luaValue(defs, "  ")},
  intents = ${luaValue(Object.fromEntries(intents.map((i) => [i.name, { name: i.name, version: i.version, yields: !!i.yields, update: !!i.update, props: i.props, result: i.result ?? null, events: i.events ?? {} }])), "  ")},
}
`;
writeFileSync(`${root}lua/intents.schema.lua`, lua);
console.log(`intents: ${intents.map((i) => `${i.name}@${i.version}`).join(" ")} → src/intents.generated.ts, lua/intents.schema.lua`);
