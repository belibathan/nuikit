// The arsenal: src/spec/api (the source) → arsenal.json + src/domains/*.ts (generated, committed).
//
//   node scripts/arsenal.mjs           write (part of the core build, after tsup)
//   node scripts/arsenal.mjs --check   exit 1 when a committed output differs (CI: idempotent)
//
// arsenal.json: domain → entries { name, side, kind, js, lua, from, signature, doc, since, status } + events + legacy +
// rules, then the registry's components and blocks grouped by the system they serve. JS signatures come from the
// built declarations (dist/*.d.ts, TypeScript compiler API); an entry whose export is missing fails the run.
import { createRequire } from "node:module";
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const repo = fileURLToPath(new URL("../../..", import.meta.url));
const require = createRequire(import.meta.url);
const check = process.argv.includes("--check");

// ── load the spec (TypeScript) through tsup's esbuild
const esbuild = createRequire(require.resolve("tsup"))("esbuild");
const bundled = await esbuild.build({ entryPoints: [`${root}src/spec/api/index.ts`], bundle: true, write: false, format: "esm", platform: "node", logLevel: "silent" });
const spec = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString("base64")}`);
const DOMAINS = spec.DOMAINS;
const problems = spec.checkSpec(DOMAINS);

// Intent kinds join the intent domain as entries (their props live in spec/api/intents/*.json).
const KINDS = ["notify", "menu", "input", "confirm", "progress", "prompt", "target", "radial", "challenge"];
for (const d of DOMAINS) {
  if (d.lua !== "intent") continue;
  for (const k of KINDS) {
    const j = JSON.parse(readFileSync(`${root}src/spec/api/intents/${k}.json`, "utf8"));
    const P = k[0].toUpperCase() + k.slice(1);
    d.entries.push({
      name: k, kind: "intent", doc: j.doc.split(/(?<=\.)\s/)[0], js: `${P}Props`, lua: `nk.intent.${k}`,
      sig: { lua: `nk.intent.${k}(props${k === "notify" || k === "prompt" ? "|string" : ""}, opts?) → ${j.yields ? "result, reason" : "NkIntent"}` },
      since: "0.7.0", status: "stable", version: j.version, yields: j.yields,
    });
  }
}

// ── the page side: every export of the package's entry points (src, so the generator runs before tsup), with its
// signature and the module that defines it
const ts = require("typescript");
const ENTRIES = { index: "index.ts", react: "react.ts", motion: "motion.ts", devtools: "devtools.tsx", module: "module.ts", boot: "boot.ts", host: "host.ts", intents: "intents.ts", "intents-react": "intents-react.ts" };
const tsconfig = ts.parseJsonConfigFileContent(ts.readConfigFile(`${root}tsconfig.json`, ts.sys.readFile).config, ts.sys, root);
const program = ts.createProgram(Object.values(ENTRIES).map((f) => `${root}src/${f}`), { ...tsconfig.options, noEmit: true });
const checker = program.getTypeChecker();
const exportsOf = new Map(); // name → { from, module, signature, value }
for (const [e, f] of Object.entries(ENTRIES)) {
  const sf = program.getSourceFile(`${root}src/${f}`);
  for (const sym of checker.getExportsOfModule(checker.getSymbolAtLocation(sf))) {
    if (exportsOf.has(sym.name)) continue;
    const real = sym.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(sym) : sym;
    const decl = real.declarations?.[0];
    let signature;
    if (decl && real.flags & (ts.SymbolFlags.Function | ts.SymbolFlags.Variable)) {
      const type = checker.getTypeOfSymbolAtLocation(real, decl);
      const sigs = type.getCallSignatures();
      signature = sigs.length
        ? `${sym.name}${checker.signatureToString(sigs[0], undefined, ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.WriteArrowStyleSignature).replace(/^(<[^(]*>)?\((.*)\) => /, "$1($2): ")}`
        : undefined;
    }
    const module = decl ? decl.getSourceFile().fileName.replace(`${root}src/`, "").replace(/\.tsx?$/, "") : e;
    exportsOf.set(sym.name, { from: e === "index" ? "nuikit-core" : `nuikit-core/${e}`, module, signature, value: !!(real.flags & ts.SymbolFlags.Value) });
  }
}

// Every value export must be claimed by one domain (js or also), or listed in spec.INTERNAL with its reason.
const claimed = new Map();
for (const d of DOMAINS)
  for (const e of d.entries)
    for (const n of [e.kind === "intent" ? null : e.js, ...(e.also ?? [])].filter(Boolean)) {
      if (claimed.has(n)) problems.push(`${d.lua}.${e.name}: js "${n}" is also claimed by ${claimed.get(n)}`);
      claimed.set(n, `${d.lua}.${e.name}`);
      if (!exportsOf.has(n)) problems.push(`${d.lua}.${e.name}: js export "${n}" not found in nuikit-core`);
    }
for (const [n, x] of exportsOf) if (x.value && !claimed.has(n) && !spec.INTERNAL[n]) problems.push(`unclaimed export "${n}" (${x.from}): add it to a domain in src/spec/api or to INTERNAL`);

const out = { $comment: "Generated by packages/core/scripts/arsenal.mjs from packages/core/src/spec/api. Do not edit.", version: JSON.parse(readFileSync(`${root}package.json`, "utf8")).version, domains: [], components: [], blocks: [] };
for (const d of DOMAINS) {
  const entries = d.entries.map((e) => {
    let from;
    let jsSig = e.sig?.js;
    if (e.js && e.kind !== "intent") {
      const x = exportsOf.get(e.js);
      if (x) {
        from = e.kind === "hook" || e.kind === "component" ? x.from : `nuikit-core/${d.js}`;
        if (x.signature) jsSig = x.signature;
      }
    }
    if (e.kind === "intent") from = "nuikit-core/intents";
    const side = e.js && e.lua ? "both" : e.js ? "js" : "lua";
    return {
      name: e.name, kind: e.kind, side, ...(e.js ? { js: e.js, from } : {}), ...(e.lua ? { lua: e.lua } : {}),
      signature: { ...(jsSig ? { js: jsSig } : {}), ...(e.sig?.lua ? { lua: e.sig.lua } : {}) },
      doc: e.doc, ...(e.only ? { only: e.only } : {}), since: e.since, status: e.status ?? "stable",
      ...(e.version ? { version: e.version, yields: e.yields } : {}),
    };
  });
  out.domains.push({ js: d.js, lua: d.lua, title: d.title, doc: d.doc, docs: d.docs, import: `nuikit-core/${d.js}`, entries, events: d.events ?? [], legacy: d.legacy ?? [], rules: d.rules ?? [] });
}

// ── the registry: components and blocks by the system they serve
const SYSTEM_OF_GROUP = { Foundations: "foundations", Layout: "foundations", HUD: "hud", "Gauges & vitals": "hud", "Lists & selection": "menus", "Dialogs & sheets": "dialogs", "Notices & prompts": "notices", Inputs: "inputs" };
const SYSTEM_OF_BLOCK = { "hud-minimal": "hud", "loading-screen": "hud", "death-screen": "hud", "job-tracker": "hud", "pause-menu": "menus", settings: "menus", "job-sheet": "menus", "job-menu": "menus", "npc-dialogue": "dialogs", bank: "dialogs", interaction: "world", garage: "world", "vehicle-shop": "world", "character-select": "world" };
export const SYSTEMS = ["foundations", "hud", "menus", "dialogs", "notices", "inputs", "world", "screens"];
const registry = JSON.parse(readFileSync(`${repo}registry.json`, "utf8"));
for (const i of registry.items) {
  if (i.meta?.hidden || !["registry:ui", "registry:block", "registry:hook"].includes(i.type)) continue;
  const row = { name: i.name, title: i.title ?? i.name, doc: (i.description ?? "").split(/(?<=\.)\s/)[0], since: i.meta?.since ?? "0.5.0", status: i.meta?.status === "unproven" ? "unproven" : "stable" };
  if (i.type === "registry:block") out.blocks.push({ ...row, system: SYSTEM_OF_BLOCK[i.name] ?? "screens" });
  else out.components.push({ ...row, kind: i.type === "registry:hook" ? "hook" : "component", system: SYSTEM_OF_GROUP[i.meta?.group] ?? "foundations" });
}
const bySystem = (a, b) => SYSTEMS.indexOf(a.system) - SYSTEMS.indexOf(b.system) || a.name.localeCompare(b.name);
out.components.sort(bySystem);
out.blocks.sort(bySystem);

if (problems.length) {
  console.error(`arsenal: ${problems.length} problem(s)\n  ${problems.join("\n  ")}`);
  process.exit(1);
}

// ── the JS entry points: src/domains/<js>.ts per domain (tsup builds each as nuikit-core/<js>). Everything a domain
// claims, re-exported from the module that defines it; a module only this domain draws from comes whole (export *),
// so its types travel with it. React hooks and components stay in nuikit-core/react (react-free domains).
const REACT = new Set(["react", "intents-react"]);
const SHARED = new Set(["index", "react", "intents-react", "intents.generated"]);
const files = { [`${root}arsenal.json`]: `${JSON.stringify(out, null, 2)}\n` };
const users = new Map(); // module → domains drawing from it
for (const d of DOMAINS) for (const e of d.entries) for (const n of [e.js, ...(e.also ?? [])]) {
  const m = n && e.kind !== "intent" && exportsOf.get(n)?.module;
  if (m) users.set(m, new Set([...(users.get(m) ?? []), d.js]));
}
for (const d of DOMAINS) {
  const named = new Map(); // module → names
  const whole = new Set();
  for (const e of d.entries) for (const n of [e.js, ...(e.also ?? [])]) {
    const x = n && e.kind !== "intent" ? exportsOf.get(n) : undefined;
    if (!x || REACT.has(x.module)) continue;
    if (!SHARED.has(x.module) && users.get(x.module).size === 1) whole.add(x.module);
    else named.set(x.module, [...(named.get(x.module) ?? []), x.value ? n : `type ${n}`]);
  }
  for (const m of whole) named.delete(m);
  // A subpath that shipped before the domains (nuikit-core/motion, /devtools, /intents, /host) keeps all it had.
  const KEPT = { motion: "motion", devtools: "devtools", intents: "intents", host: "host" };
  if (KEPT[d.js]) { whole.add(KEPT[d.js]); named.delete(KEPT[d.js]); }
  const lines = [`// nuikit-core/${d.js}: ${d.title}. Generated by scripts/arsenal.mjs from src/spec/api/${d.js}.ts. Do not edit.`, `// ${d.doc}`];
  // a whole module: every export but the test hooks (__reset…), types included
  for (const m of [...whole].sort()) {
    const sf = program.getSourceFile(`${root}src/${m}${existsSync(`${root}src/${m}.tsx`) ? ".tsx" : ".ts"}`);
    const own = (x) => (x.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(x) : x).declarations?.[0]?.getSourceFile() === sf;
    const all = checker.getExportsOfModule(checker.getSymbolAtLocation(sf)).filter((x) => !x.name.startsWith("__") && (x.name === "default" || own(x)));
    const isValue = (x) => !!((x.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(x) : x).flags & ts.SymbolFlags.Value);
    const names = all.map((x) => (x.name === "default" ? "default" : isValue(x) ? x.name : `type ${x.name}`)).sort((a, b) => a.replace("type ", "").localeCompare(b.replace("type ", "")));
    named.set(m, names);
  }
  for (const [m, names] of [...named].sort()) lines.push(`export { ${[...new Set(names)].sort((a, b) => a.replace("type ", "").localeCompare(b.replace("type ", ""))).join(", ")} } from "../${m}";`);
  files[`${root}src/domains/${d.js}.ts`] = `${lines.join("\n")}\n`;
}
// package.json exports: one per domain (an existing subpath keeps its entry; tsup.config builds src/domains/*).
const pkgFile = `${root}package.json`;
const pkg = JSON.parse(readFileSync(pkgFile, "utf8"));
for (const d of DOMAINS) pkg.exports[`./${d.js}`] ??= { types: `./dist/${d.js}.d.ts`, import: `./dist/${d.js}.js` };
files[pkgFile] = `${JSON.stringify(pkg, null, 2)}\n`;
let drift = false;
for (const [file, text] of Object.entries(files)) {
  const now = existsSync(file) ? readFileSync(file, "utf8") : "";
  if (now === text) continue;
  if (check) {
    console.error(`arsenal: ${file.replace(repo, "")} is stale (run node packages/core/scripts/arsenal.mjs)`);
    drift = true;
  } else {
    mkdirSync(file.replace(/\/[^/]+$/, ""), { recursive: true });
    writeFileSync(file, text);
  }
}
if (drift) process.exit(1);
console.log(`arsenal: ${out.domains.map((d) => `${d.lua} ${d.entries.length}`).join(" · ")} · ${out.components.length} components · ${out.blocks.length} blocks`);
